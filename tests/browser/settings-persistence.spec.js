import { test, expect } from '@playwright/test';
import { installKeyboard, connectKeyboard } from './keyboard-fixture.js';

test.beforeEach(async ({ page }) => {
  await installKeyboard(page); await page.goto('/'); await connectKeyboard(page);
});

test('applied settings survive loss of volatile memory and reconnect', async ({ page }) => {
  await page.locator('#nav [data-view="perf"]').click();
  await page.locator('#gamePreset').selectOption('fps-fast');
  await page.locator('#btnGamePresetApply').click();
  await expect(page.locator('#btnGamePresetApply')).toHaveText('Preset applicato');
  await expect(page.locator('#btnGamePresetApply')).toBeDisabled();
  await expect(page.locator('#presetStatus')).toHaveText('Preset salvato e verificato');
  await page.locator('#nav [data-view="keymap"]').click();
  await page.locator('#layerSeg [data-layer="1"]').click();
  await page.locator('#kbdMap [data-key="40"]').click();
  await page.locator('#mapTarget').selectOption('76');
  await page.locator('#btnMapApply').click();
  await expect(page.locator('#btnMapApply')).toBeEnabled();
  await page.locator('#nav [data-view="rgb"]').click();
  await page.locator('#rgbShortcuts summary').click();
  await page.locator('#btnMapCompleteRgb').click();
  await page.locator('#btnMapSaveLayout').click();
  await expect(page.locator('#btnMapSaveLayout')).toBeDisabled();
  await page.locator('[data-rgb-select="wasd"]').click();
  await page.locator('#rgbHex').fill('#1234ab');
  await page.locator('#rgbHex').press('Tab');
  await page.locator('#btnRgbPaint').click();
  await page.locator('#btnRgbApply').click();
  await expect(page.locator('#btnRgbApply')).toBeEnabled();
  await page.locator('#nav [data-view="socd"]').click();
  await page.locator('#btnSocdApply').click();
  await expect(page.locator('#btnSocdApply')).toBeEnabled();
  await page.locator('#nav [data-view="perf"]').click();
  await page.locator('#kbdPerf [data-key="30"]').click();
  await expect(page.locator('#btnPerfApply')).toBeEnabled();
  await page.locator('#perfMode').selectOption('global');
  await page.locator('#btnPerfApply').click();
  await expect(page.locator('#btnPerfApply')).toBeEnabled();
  await page.locator('#nav [data-view="advanced"]').click();
  await page.locator('#kbdAdvanced [data-key="29"]').click();
  await page.locator('[data-advanced-mode="dks"]').click();
  await page.locator('#btnAdvancedApply').click();
  await expect(page.locator('#btnAdvancedApply')).toBeEnabled();
  await expect(page.locator('#toast')).toContainText('Configurazione assegnata');
  await page.locator('#kbdAdvanced [data-key="28"]').click();
  await page.locator('[data-advanced-mode="macro"]').click();
  await page.locator('#btnMacroRecord').click();
  await page.keyboard.press('b'); await page.keyboard.press('Escape');
  await page.locator('#btnAdvancedApply').click();
  await expect(page.locator('#btnAdvancedApply')).toBeEnabled();
  await expect(page.locator('#toast')).toContainText('Configurazione assegnata');
  await page.locator('#nav [data-view="settings"]').click();
  await page.locator('#deviceSystem').selectOption('mac');
  await page.locator('#btnSystemApply').click();
  await expect(page.locator('#btnSystemApply')).toBeEnabled();
  await page.locator('#deviceSuperResponse').check();
  await page.locator('#btnSuperResponse').click();
  await expect(page.locator('#btnSuperResponse')).toBeEnabled();
  const before = await page.evaluate(() => window.__keyboardFixture.snapshot());
  await page.evaluate(() => window.__keyboardFixture.powerCycle());
  await expect(page.locator('#connectionScreen')).toBeVisible();
  await connectKeyboard(page);
  expect(await page.evaluate(() => window.__keyboardFixture.snapshot())).toEqual(before);
  await page.locator('#nav [data-view="keymap"]').click();
  await page.locator('#layerSeg [data-layer="1"]').click();
  await expect(page.locator('#kbdMap [data-key="40"] .key-main')).toHaveText('Del');
});

test('profile selection and calibration completion request a persistent save', async ({ page }) => {
  await page.locator('#nav [data-view="settings"]').click();
  await page.locator('#profileSeg [data-profile="1"]').click();
  await expect(page.locator('#profileSeg [data-profile="1"]')).toBeEnabled();
  const count = await page.evaluate(() => window.__keyboardFixture.saveCount);
  expect(count).toBe(1);
  await page.locator('#btnCalibrationStart').click();
  await expect(page.locator('#btnCalibrationEnd')).toBeEnabled();
  expect(await page.evaluate(() => window.__keyboardFixture.saveCount)).toBe(count);
  await page.locator('#btnCalibrationEnd').click();
  await expect(page.locator('#btnCalibrationStart')).toBeEnabled();
  expect(await page.evaluate(() => window.__keyboardFixture.saveCount)).toBe(count + 1);
  await page.evaluate(() => window.__keyboardFixture.powerCycle());
  await connectKeyboard(page);
  await expect(page.locator('#profileSeg [data-profile="1"]')).toHaveClass(/active/);
});

test('read-only actions never commit and failed save preserves the layout draft for retry', async ({ page }) => {
  await page.locator('#nav [data-view="keymap"]').click();
  expect(await page.evaluate(() => window.__keyboardFixture.saveCount)).toBe(0);
  await page.locator('#btnMapEdit').click();
  await page.locator('#layerSeg [data-layer="1"]').click();
  await page.locator('#mapChoices [data-code="76"]').click();
  await page.locator('#kbdMap [data-key="40"]').click();
  await page.evaluate(() => { window.__keyboardFixture.saveFailure = true; });
  await page.locator('#btnMapSaveLayout').click();
  await expect(page.locator('#toast')).toContainText('Salvataggio permanente non confermato');
  await expect(page.locator('#mapLayoutStatus')).toHaveText('Modifiche da applicare: 1');
  await expect(page.locator('#btnMapSaveLayout')).toBeEnabled();
  await page.evaluate(() => { window.__keyboardFixture.saveFailure = false; });
  await page.locator('#btnMapSaveLayout').click();
  await expect(page.locator('#toast')).toHaveText('Layout salvato e verificato');
  expect(await page.evaluate(() => window.__keyboardFixture.saveCount)).toBe(1);
  await page.evaluate(() => window.__keyboardFixture.powerCycle());
  await connectKeyboard(page);
  expect(await page.evaluate(() => window.__keyboardFixture.registers.get('40:1'))).toBe(76);
});
